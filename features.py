import pandas as pd
import numpy as np
import json

def build_features(df):
    """
    Constructs calendar and historical inputs for each hour.
    """
    print("Building calendar and historical features...")
    df_feat = df.copy()
    
    # 1. Known calendar inputs (ensure they are strings for one-hot encoding later)
    df_feat['weekday_encoded'] = df_feat['weekday'].astype(str)
    df_feat['hour_encoded'] = df_feat['hr'].astype(str)
    df_feat['month_encoded'] = df_feat['mnth'].astype(str)
    
    # Set the target timestamp as the index for exact lookups
    df_indexed = df_feat.set_index('timestamp')
    
    # Initialize historical columns
    hist_cols = ['prev_hour_cnt', 'prev_day_cnt', 'prev_week_cnt', 'prev_24h_mean', 
                 'prev_hour_temp', 'prev_hour_hum', 'prev_hour_wind']
    for col in hist_cols:
        df_feat[col] = np.nan

    # 2. Exact timestamp lookup for historical values
    for idx, row in df_feat.iterrows():
        t = row['timestamp']
        
        # t minus 1 hour
        t_minus_1h = t - pd.Timedelta(hours=1)
        if t_minus_1h in df_indexed.index:
            df_feat.at[idx, 'prev_hour_cnt'] = df_indexed.loc[t_minus_1h, 'cnt']
            df_feat.at[idx, 'prev_hour_temp'] = df_indexed.loc[t_minus_1h, 'temp']
            df_feat.at[idx, 'prev_hour_hum'] = df_indexed.loc[t_minus_1h, 'hum']
            df_feat.at[idx, 'prev_hour_wind'] = df_indexed.loc[t_minus_1h, 'windspeed']
            
        # t minus 24 hours
        t_minus_24h = t - pd.Timedelta(hours=24)
        if t_minus_24h in df_indexed.index:
            df_feat.at[idx, 'prev_day_cnt'] = df_indexed.loc[t_minus_24h, 'cnt']
            
        # t minus 168 hours
        t_minus_168h = t - pd.Timedelta(hours=168)
        if t_minus_168h in df_indexed.index:
            df_feat.at[idx, 'prev_week_cnt'] = df_indexed.loc[t_minus_168h, 'cnt']
            
        # Mean of previous 24 hours (Requires exactly 24 completed hours)
        start_24h = t - pd.Timedelta(hours=24)
        end_24h = t - pd.Timedelta(hours=1)
        mask = (df_indexed.index >= start_24h) & (df_indexed.index <= end_24h)
        past_24h_slice = df_indexed.loc[mask]
        
        if len(past_24h_slice) == 24:
            df_feat.at[idx, 'prev_24h_mean'] = past_24h_slice['cnt'].mean()

    # 3. Create missing flags
    for col in hist_cols:
        df_feat[f'{col}_missing_flag'] = df_feat[col].isna().astype(int)

    return df_feat, hist_cols


def fit_preprocessing(df_featured, hist_cols):
    """
    Learns medians for imputation from the Training set ONLY.
    Learns categorical encoding columns from the Training set ONLY.
    Saves these rules to be applied later.
    """
    print("Learning preprocessing rules from Training data...")
    # Filter only training data
    df_train = df_featured[df_featured['period'] == 'Training'].copy()
    
    # Calculate median for each historical column
    medians = {}
    for col in hist_cols:
        medians[col] = float(df_train[col].median())
        
    # Fit One-Hot Encoding on training data to know the exact columns
    cat_cols = ['hour_encoded', 'weekday_encoded', 'month_encoded']
    df_train_encoded = pd.get_dummies(df_train, columns=cat_cols)
    
    # Save the exact column names generated by get_dummies
    encoded_features = [c for c in df_train_encoded.columns if any(c.startswith(prefix) for prefix in cat_cols)]
    
    # Save to config file
    preprocessing_rules = {
        "medians": medians,
        "encoded_columns": encoded_features
    }
    
    with open("config.json", "r") as f:
        config = json.load(f)
        
    config["preprocessing"] = preprocessing_rules
    
    with open("config.json", "w") as f:
        json.dump(config, f, indent=4)
        
    print("-> Medians and encoding rules saved to config.json.")
    return preprocessing_rules


def transform_features(df_featured, hist_cols):
    """
    Applies the saved medians and encoding rules to all data.
    """
    print("Applying preprocessing rules to all data...")
    with open("config.json", "r") as f:
        config = json.load(f)
    
    medians = config["preprocessing"]["medians"]
    expected_cols = config["preprocessing"]["encoded_columns"]
    
    df_transformed = df_featured.copy()
    
    # 1. Fill missing values with saved medians
    for col in hist_cols:
        df_transformed[col] = df_transformed[col].fillna(medians[col])
        
    # 2. Apply One-Hot Encoding
    cat_cols = ['hour_encoded', 'weekday_encoded', 'month_encoded']
    df_transformed = pd.get_dummies(df_transformed, columns=cat_cols)
    
    # Ensure all expected columns exist (fill with 0 if missing in validation/test)
    for col in expected_cols:
        if col not in df_transformed.columns:
            df_transformed[col] = 0
            
    # Keep only the encoded columns and the historical columns + flags + target + base info
    # We will need these numeric columns for the regression models
    flags = [f"{col}_missing_flag" for col in hist_cols]
    base_cols = ['timestamp', 'period', 'cnt', 'workingday', 'holiday']
    
    final_cols = base_cols + hist_cols + flags + expected_cols
    
    print("Finished transforming features!")
    return df_transformed[final_cols]


